#!/usr/bin/env node
/*
 * Builds emoji-data.js — the full Unicode emoji set for Muff-Mojo.
 *
 *   node tools/build-emoji-data.mjs
 *
 * Inputs (all in tools/):
 *   vendor/unicode-emoji-json-<v>.json  every fully-qualified emoji: name, group, skin-tone support
 *                                       (npm: unicode-emoji-json, data-by-emoji.json)
 *   vendor/emojilib-<v>.json            keywords per emoji (npm: emojilib, dist/emoji-en-US.json)
 *   curated.json                        our hand-picked trigger words; these emojis rank first
 *
 * To update: drop newer vendor files in tools/vendor/, bump the names below, re-run.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const UNICODE = 'vendor/unicode-emoji-json-0.9.0.json';
const EMOJILIB = 'vendor/emojilib-4.0.3.json';

const read = (p) => JSON.parse(readFileSync(join(here, p), 'utf8'));
const unicode = read(UNICODE);
const emojilib = read(EMOJILIB);
const curated = read('curated.json');

const GROUPS = [
  ['smileys', 'Smileys & Emotion', '😀'],
  ['people', 'People & Body', '👋'],
  ['animals', 'Animals & Nature', '🐶'],
  ['food', 'Food & Drink', '🍕'],
  ['travel', 'Travel & Places', '✈️'],
  ['activities', 'Activities', '⚽'],
  ['objects', 'Objects', '💡'],
  ['symbols', 'Symbols', '❤️'],
  ['flags', 'Flags', '🏁']
];
const groupIndex = new Map(GROUPS.map(([, label], i) => [label, i]));

// Compare emoji ignoring variation selectors (curated lists may write ❤ or ❤️).
const bare = (e) => e.replace(/️/g, '');
const curatedByBare = new Map(curated.map((row, i) => [bare(row[0]), { rank: i, words: row.slice(1) }]));

// Trigger words must be a single typed token: letters, digits, underscore.
const clean = (w) => String(w).toLowerCase().trim().replace(/[\s\-]+/g, '_').replace(/[^\p{L}\p{N}_+]/gu, '');

// Filler words from official names that would only add noise as keywords.
const STOP = new Set(['with', 'and', 'the', 'for', 'from', 'over', 'out', 'into', 'without', 'one', 'two', 'three']);

const rows = [];
const seenCurated = new Set();
for (const [emoji, info] of Object.entries(unicode)) {
  const g = groupIndex.get(info.group);
  if (g === undefined) throw new Error(`Unknown group "${info.group}" for ${emoji}`);
  const cur = curatedByBare.get(bare(emoji));
  if (cur) seenCurated.add(bare(emoji));

  // Order matters: the first word is the display name; curated words come first.
  const words = [];
  const add = (w) => { const c = clean(w); if (c && !words.includes(c)) words.push(c); };
  (cur ? cur.words : []).forEach(add);
  add(info.slug);
  (emojilib[emoji] || []).forEach(add);
  // also the individual words of the official name ("smiling face with hearts" → hearts, …)
  info.name.split(/[\s:,]+/).forEach((w) => w.length > 2 && !STOP.has(w.toLowerCase()) && add(w));

  const flags = [];
  if (info.skin_tone_support) flags.push('s');
  // a one-word official name ("pizza", "rocket") is a good typing trigger; multi-word ones aren't
  // (flags count by their country name: "india" → 🇮🇳)
  let slug = clean(info.slug);
  if (info.group === 'Flags' && slug.startsWith('flag_')) { slug = slug.slice(5); add(slug); }
  if (slug && !slug.includes('_')) flags.push('n' + words.indexOf(slug));
  if (cur) flags.push('c' + cur.rank, 'k' + new Set(cur.words.map(clean).filter(Boolean)).size);
  rows.push([emoji, g, words.join(' '), flags.join(' ')].join('\t'));
}

const missing = curated.filter((r) => !seenCurated.has(bare(r[0]))).map((r) => r[0]);
if (missing.length) console.warn('Curated emoji not in Unicode data (skipped):', missing.join(' '));

const out = `/* Generated by tools/build-emoji-data.mjs — do not edit by hand. ${rows.length} emoji.
 * Sources: ${UNICODE.replace('vendor/', '')} (MIT), ${EMOJILIB.replace('vendor/', '')} (MIT), tools/curated.json */
globalThis.MuffMojoEmojiData = {
  groups: ${JSON.stringify(GROUPS)},
  // emoji \\t group index \\t trigger words (first = display name) \\t flags
  // flags: s = supports skin tones, c<n> = hand-picked emoji #n, k<n> = its first n words are hand-picked,
  //        n<i> = word #i is its one-word official name
  // Plain typing only reacts to hand-picked words and one-word names; ":search" uses every word.
  rows: ${JSON.stringify(rows.join('\n'))}
};
`;
writeFileSync(join(here, '..', 'emoji-data.js'), out);
console.log(`emoji-data.js: ${rows.length} emoji, ${seenCurated.size} hand-picked, ${(out.length / 1024).toFixed(0)} KB`);
